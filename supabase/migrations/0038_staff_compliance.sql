--      anchored on employee.hire_date, clinical titles only; its own cron tick.
--   3. trigger_kind='on_event' becomes real (D-016 left it explicitly unimplemented):
--      cadence rules can subscribe to outbox event types; the domain_event trigger
--      materializes the obligation in the same transaction as the event. First
