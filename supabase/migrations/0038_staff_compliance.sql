--   1. Credential catalog repair + expansion toward the COMAR 10.07.05.10 personnel
--      file. REPAIRS: CPR interval 365→730 (AHA BLS certifies for two years — the
--      seeded 365 had no regulatory basis); TB re-screen interval flagged as assumed.
--      Every invented interval carries an advisor_note; nothing is auto-cited (D-017).
--   2. Staff-side cadence materialization: the 0009 evaluator transitions staff
--      obligations but never created them ("generated by a later migration" — this is
